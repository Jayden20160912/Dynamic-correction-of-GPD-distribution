"""
Merge main.py + gpd_core.py into ONE file for QuantConnect: qc_single_file/main.py

Why: QuantConnect's free tier limits each file to 32,000 characters, and importing a second
project file (gpd_core.py) does not always work there. The merged file needs no imports
from other project files.

To stay under the limit, the gpd_core part loses its comments and docstrings (the code is
unchanged; the readable version stays in gpd_core.py). main.py, including all comments of
the CONFIG section, is copied as is.

Usage (after every change to main.py or gpd_core.py):
    python build_single_file.py
then paste qc_single_file/main.py into QuantConnect as main.py (the only file needed).
"""

import ast
from pathlib import Path

HERE = Path(__file__).resolve().parent
LIMIT = 32_000


def strip_docstrings(tree):
    for node in ast.walk(tree):
        if isinstance(node, (ast.Module, ast.FunctionDef, ast.ClassDef, ast.AsyncFunctionDef)):
            body = node.body
            if body and isinstance(body[0], ast.Expr) and isinstance(getattr(body[0], "value", None), ast.Constant) \
                    and isinstance(body[0].value.value, str):
                node.body = body[1:] or [ast.Pass()]
    return tree


def main():
    core_src = (HERE / "gpd_core.py").read_text()
    core = ast.unparse(strip_docstrings(ast.parse(core_src)))     # removes comments + docstrings

    main_src = (HERE / "main.py").read_text()
    doc = ast.get_docstring(ast.parse(main_src), clean=False)
    if doc is not None:                                            # replace the long usage notes
        start = main_src.index('"""'); end = main_src.index('"""', start + 3) + 3
        main_src = (main_src[:start] + '"""GPD-mixture tail-risk strategy for QuantConnect (single file).\n'
                    'Generated by build_single_file.py from main.py + gpd_core.py; see those files for notes."""'
                    + main_src[end:])
    main_lines = main_src.splitlines(keepends=True)
    out, inserted = [], False
    for line in main_lines:
        if line.startswith("from gpd_core import"):
            if not inserted:
                out.append("\n# ---- computation (generated from gpd_core.py by build_single_file.py; "
                           "edit gpd_core.py, not this block) ----\n")
                out.append(core + "\n# ---- end of gpd_core.py ----\n\n")
                inserted = True
            continue
        out.append(line)
    if not inserted:
        raise SystemExit("main.py has no 'from gpd_core import' line")
    text = "".join(out)
    ast.parse(text)                                                # must still be valid Python

    dest = HERE / "qc_single_file" / "main.py"
    dest.parent.mkdir(exist_ok=True)
    dest.write_text(text)
    n = len(text)
    print(f"wrote {dest}  ({n:,} characters, limit {LIMIT:,})")
    if n > LIMIT:
        raise SystemExit(f"TOO LONG by {n - LIMIT:,} characters: shorten comments in main.py")


if __name__ == "__main__":
    main()
